import { lstatSync, readFileSync, rmSync, type Stats } from 'node:fs'
import { join } from 'node:path'

const LEGACY_MANAGED_PROTOCOL_PREFIX = '# Hive Team Protocol\n\nThis file is auto-generated by Hive'
const RECOVERABLE_CLEANUP_ERROR_CODES = new Set([
  'EACCES',
  'EBUSY',
  'EISDIR',
  'ELOOP',
  'ENOENT',
  'ENOTDIR',
  'EPERM',
])

const isRecoverableCleanupError = (error: unknown): boolean =>
  error instanceof Error &&
  'code' in error &&
  typeof error.code === 'string' &&
  RECOVERABLE_CLEANUP_ERROR_CODES.has(error.code)

const readRetiredPathStats = (path: string): Stats | null => {
  try {
    return lstatSync(path)
  } catch (error) {
    if (isRecoverableCleanupError(error)) return null
    throw error
  }
}

const removeRetiredFile = (path: string): void => {
  const stats = readRetiredPathStats(path)
  if (!stats || (!stats.isFile() && !stats.isSymbolicLink())) return
  try {
    rmSync(path)
  } catch (error) {
    if (!isRecoverableCleanupError(error)) throw error
  }
}

export const removeRetiredWorkspaceFiles = (workspacePath: string) => {
  const hiveDir = join(workspacePath, '.hive')
  removeRetiredFile(join(hiveDir, 'tasks.md'))

  const protocolPath = join(hiveDir, 'PROTOCOL.md')
  const protocolStats = readRetiredPathStats(protocolPath)
  if (!protocolStats || (!protocolStats.isFile() && !protocolStats.isSymbolicLink())) return
  try {
    if (readFileSync(protocolPath, 'utf8').startsWith(LEGACY_MANAGED_PROTOCOL_PREFIX)) {
      removeRetiredFile(protocolPath)
    }
  } catch (error) {
    if (!isRecoverableCleanupError(error)) throw error
  }
}
