import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { afterEach, describe, expect, test } from 'vitest'

import { removeRetiredWorkspaceFiles } from '../../src/server/retired-workspace-files.js'

const tempDirs: string[] = []

const newWorkspace = () => {
  const path = mkdtempSync(join(tmpdir(), 'yive-retired-workspace-files-test-'))
  tempDirs.push(path)
  return path
}

afterEach(() => {
  for (const path of tempDirs.splice(0)) rmSync(path, { force: true, recursive: true })
})

describe('retired Workspace files', () => {
  test('deletes only the managed .hive tasks file', () => {
    const workspace = newWorkspace()
    const hiveDir = join(workspace, '.hive')
    mkdirSync(hiveDir, { recursive: true })
    writeFileSync(join(hiveDir, 'tasks.md'), '- [ ] retired\n', 'utf8')
    writeFileSync(join(workspace, 'tasks.md'), 'root file stays\n', 'utf8')
    writeFileSync(join(hiveDir, 'mobile-attachments.json'), '{"attachments":[]}', 'utf8')
    writeFileSync(join(hiveDir, 'notes.md'), 'unrelated data\n', 'utf8')

    removeRetiredWorkspaceFiles(workspace)

    expect(existsSync(join(hiveDir, 'tasks.md'))).toBe(false)
    expect(readFileSync(join(workspace, 'tasks.md'), 'utf8')).toBe('root file stays\n')
    expect(readFileSync(join(hiveDir, 'mobile-attachments.json'), 'utf8')).toBe(
      '{"attachments":[]}'
    )
    expect(readFileSync(join(hiveDir, 'notes.md'), 'utf8')).toBe('unrelated data\n')
  })

  test('removes an existing Yive-managed protocol file', () => {
    const workspace = newWorkspace()
    const protocolPath = join(workspace, '.hive', 'PROTOCOL.md')
    mkdirSync(join(workspace, '.hive'), { recursive: true })
    writeFileSync(
      protocolPath,
      '# Hive Team Protocol\n\nThis file is auto-generated by Hive on every workspace open.\n',
      'utf8'
    )

    removeRetiredWorkspaceFiles(workspace)

    expect(existsSync(protocolPath)).toBe(false)
  })

  test('preserves a user-authored file at the retired protocol path', () => {
    const workspace = newWorkspace()
    const protocolPath = join(workspace, '.hive', 'PROTOCOL.md')
    const content = '# My project protocol\n'
    mkdirSync(join(workspace, '.hive'), { recursive: true })
    writeFileSync(protocolPath, content, 'utf8')

    removeRetiredWorkspaceFiles(workspace)

    expect(readFileSync(protocolPath, 'utf8')).toBe(content)
  })

  test('preserves non-file retired paths without blocking cleanup', () => {
    const workspace = newWorkspace()
    const tasksPath = join(workspace, '.hive', 'tasks.md')
    const protocolPath = join(workspace, '.hive', 'PROTOCOL.md')
    mkdirSync(tasksPath, { recursive: true })
    mkdirSync(protocolPath, { recursive: true })
    writeFileSync(join(tasksPath, 'keep.txt'), 'unrelated directory data\n', 'utf8')

    removeRetiredWorkspaceFiles(workspace)
    expect(readFileSync(join(tasksPath, 'keep.txt'), 'utf8')).toBe('unrelated directory data\n')
    expect(existsSync(protocolPath)).toBe(true)
  })
})
